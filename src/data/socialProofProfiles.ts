const SESSION_KEY = 'otherme_social_proof_profiles'

export function getRandomSocialProofProfiles(count = 3): SocialProofProfile[] {
  try {
    const cached = sessionStorage.getItem(SESSION_KEY)
    if (cached) {
      const parsed = JSON.parse(cached) as SocialProofProfile[]
      if (Array.isArray(parsed) && parsed.length === count) return parsed
    }
  } catch { /* sessionStorage indisponible */ }

  const pool = [...socialProofProfiles]
  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[pool[i], pool[j]] = [pool[j], pool[i]]
  }
  const selected = pool.slice(0, count)

  try {
    sessionStorage.setItem(SESSION_KEY, JSON.stringify(selected))
  } catch { /* sessionStorage indisponible */ }

  return selected
}
